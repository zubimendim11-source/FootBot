async def start_interview(bot, dp, user_id, sit_key): # Добавили dp сюда
    # Теперь dp берется из аргументов, а не из импорта
    state_ctx = dp.fsm.get_context(bot, user_id=user_id, chat_id=user_id)
    
    question = random.choice(QUESTIONS[sit_key])
    await state_ctx.set_state(InterviewStates.waiting_answer_1)
    await state_ctx.update_data(current_sit=sit_key, q1=question)
    
    msg = f"🎤 <b>ЭКСКЛЮЗИВНОЕ ИНТЕРВЬЮ</b>\n\n<b>Журналист:</b> {question}"
    try:
        await bot.send_message(user_id, msg, parse_mode="HTML")
    except Exception as e:
        print(f"Ошибка отправки интервью: {e}")

@router.message(InterviewStates.waiting_answer_1)
async def handle_ans_1(m: types.Message, state: FSMContext):
    if any(word in m.text.lower() for word in BAD_WORDS):
        await m.answer("⚠️ Интервью прервано за мат!")
        return await state.clear()
    
    next_q = random.choice(FOLLOW_UP)
    await state.update_data(a1=m.text, q2=next_q)
    await m.answer(f"🎤 <b>Журналист:</b>\n{next_q}", parse_mode="HTML")
    await state.set_state(InterviewStates.waiting_answer_2)

