def get_db():
    conn = sqlite3.connect('football_bot.db', check_same_thread=False, timeout=20)
    conn.execute('PRAGMA busy_timeout = 5000')
    return conn

def club_generator(clubs, exclude=None):
    # Фильтруем клубы участников, чтобы они не выпадали как "третьи лица"
    pool = [c for c in clubs if c not in (exclude or [])]
    if not pool: pool = ["Сборная мира", "Пенсионеры", "Клуб НН"]
    random.shuffle(pool)
    while True:
        for club in pool: yield club
        random.shuffle(pool)

